#!/usr/bin/env python3
"""Run every experiment the paper's tables need, in one command.

Resumable: a run whose Phase 4 result file already exists is skipped, so an
interrupted session continues where it stopped rather than starting over.

Each variant differs from the main run in exactly one config value, which is
what makes the resulting comparison an ablation rather than a relabelling:

    main            state = GNN embeddings,  lambda = 0
    ablation_raw    state = raw features,    lambda = 0     <- does the graph help?
    ablation_cate   state = GNN embeddings,  lambda = 0.5   <- does CATE shaping help?

Usage
-----
    python scripts/run_paper_experiments.py --config configs/obd_fast.yaml
    python scripts/run_paper_experiments.py --config configs/obd_fast.yaml --seeds 42 43 44
    python scripts/run_paper_experiments.py --config configs/obd_fast.yaml --variants main
    python scripts/run_paper_experiments.py --config configs/obd_fast.yaml --dry-run
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import traceback
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from gcrl.cli import (  # noqa: E402
    cate_artefact_path,
    command_phase1,
    command_phase2,
    command_phase3,
    command_phase4,
)
from gcrl.config import load_config  # noqa: E402
from gcrl.logging_utils import configure_logging, get_logger  # noqa: E402

logger = get_logger("run_paper_experiments")


@dataclass
class Variant:
    """One experimental arm: a name plus the config overrides that define it."""

    name: str
    state_source: str
    cate_reward_weight: float
    description: str
    needs_causal: bool = False


VARIANTS: dict[str, Variant] = {
    "main": Variant(
        "main", "gnn_embeddings", 0.0,
        "Proposed pipeline: GNN state, unshaped reward",
    ),
    "ablation_raw": Variant(
        "ablation_raw", "raw_features", 0.0,
        "Remove the graph: raw tabular state, unshaped reward",
    ),
    "ablation_cate": Variant(
        "ablation_cate", "gnn_embeddings", 0.5,
        "Add causal reward shaping: GNN state, r + 0.5*CATE",
        needs_causal=True,
    ),
}


@dataclass
class RunRecord:
    variant: str
    seed: int
    status: str
    seconds: float
    error: str | None = None
    phases: list[str] = field(default_factory=list)
    #: Full traceback of a failure, so ``experiment_runs.json`` is enough to
    #: diagnose an unattended run without going back to the console logs.
    traceback: str | None = None


class _Args:
    """Mimics the argparse namespace the gcrl.cli commands expect."""

    def __init__(self, config: Path, seed: int, data_root: Path | None, log_level: str):
        self.config = config
        self.seed = seed
        self.data_root = data_root
        self.log_level = log_level


def _variant_config_path(base: Path, variant: Variant) -> Path:
    """Write a child config that inherits from ``base`` and applies the variant.

    Written beside the base config, because ``extends:`` resolves relative to the
    config's own directory.
    """
    path = base.parent / f"_generated_{base.stem}_{variant.name}.yaml"

    lines = [
        f"# Generated by run_paper_experiments.py -- variant '{variant.name}'.",
        f"# {variant.description}",
        f"extends: {base.name}",
        "",
        f"experiment_name: {base.stem}_{variant.name}",
        "",
        "rl:",
        f"  state_source: {variant.state_source}",
        f"  cate_reward_weight: {variant.cate_reward_weight}",
    ]
    if variant.needs_causal:
        lines += ["", "causal:", "  enabled: true"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _result_exists(config_path: Path, seed: int) -> bool:
    config = load_config(config_path)
    return (
        Path(config.paths.results) / f"phase4_ope_{config.experiment_name}_seed{seed}.json"
    ).exists()


def run_one(config_path: Path, seed: int, data_root: Path | None, log_level: str) -> RunRecord:
    """Run every applicable phase for one (config, seed)."""
    config = load_config(config_path)
    args = _Args(config_path, seed, data_root, log_level)

    # Only run the phases this variant actually consumes. The three arms differ
    # in rl.* alone, while Phases 1 and 2 depend on the data and the seed -- so
    # running them per arm retrained identical encoders and refitted identical
    # forests. Their artefacts are keyed by dataset and seed and are shared.
    phases = []

    if config.rl.state_source == "gnn_embeddings":
        phases.append(("phase1", command_phase1))
    else:
        logger.info("skipping phase1: state_source=%s does not use embeddings",
                    config.rl.state_source)

    if config.causal.enabled:
        # Ask for the EXACT artefact Phase 3 will later open, not a
        # dataset-keyed summary file. Those are different keys: the summary is
        # named by dataset and seed, while the CATE vector is fingerprinted by
        # everything that produced it. A leftover summary from a smoke run
        # (which shares dataset.name) therefore satisfied this check while the
        # full run's CATE did not exist -- Phase 2 was skipped, and Phase 3 then
        # died with "CATE estimates not found". Skipping work is only safe when
        # the thing being skipped has already produced the exact file its
        # consumer will look for.
        cate_path = cate_artefact_path(config, config.rl.cate_estimator, seed)
        cate_done = cate_path.exists()
        if cate_done:
            logger.info("skipping phase2: %s already exists", cate_path.name)
        else:
            phases.append(("phase2", command_phase2))

    phases += [("phase3", command_phase3), ("phase4", command_phase4)]

    started = time.time()
    completed: list[str] = []
    for name, function in phases:
        logger.info("-" * 60)
        logger.info("%s | seed %d | %s", config_path.stem, seed, name)
        logger.info("-" * 60)
        try:
            code = function(args)
        except Exception as exc:
            # The traceback goes to ERROR, not DEBUG. A one-line message like
            # "not enough values to unpack (expected 2, got 1)" is unactionable
            # without the frame it came from, and an unattended overnight run is
            # exactly when nobody is watching at DEBUG level. Hiding it costs a
            # whole re-run to recover information that was already in hand.
            detail = traceback.format_exc()
            logger.error(
                "%s failed: %s\n%s\n%s\n%s",
                name, exc, "-" * 70, detail.rstrip(), "-" * 70,
            )
            return RunRecord(
                config_path.stem, seed, "failed", time.time() - started,
                f"{name}: {exc}", completed, traceback=detail,
            )
        if code != 0:
            return RunRecord(
                config_path.stem, seed, "failed", time.time() - started,
                f"{name} exited with code {code}", completed,
            )
        completed.append(name)

    return RunRecord(config_path.stem, seed, "ok", time.time() - started, None, completed)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, required=True, help="base dataset config")
    parser.add_argument("--seeds", type=int, nargs="+", default=[42])
    parser.add_argument(
        "--variants", nargs="+", default=["main"], choices=sorted(VARIANTS) + ["all"],
        help="which arms to run (default: main only)",
    )
    parser.add_argument("--data-root", type=Path, default=None)
    parser.add_argument("--log-level", default="INFO")
    parser.add_argument("--force", action="store_true", help="rerun even if results exist")
    parser.add_argument("--dry-run", action="store_true", help="list the runs and exit")
    args = parser.parse_args()

    base = args.config.resolve()
    selected = sorted(VARIANTS) if "all" in args.variants else args.variants

    configure_logging(Path("logs"), f"experiments_{base.stem}")

    plan = [
        (_variant_config_path(base, VARIANTS[v]), VARIANTS[v], seed)
        for v in selected
        for seed in args.seeds
    ]

    logger.info("=" * 60)
    logger.info("Planned runs: %d", len(plan))
    for path, variant, seed in plan:
        done = "" if args.force or not _result_exists(path, seed) else "   [results exist, will skip]"
        logger.info("  %-28s seed %-4d  %s%s", variant.name, seed, variant.description, done)
    logger.info("=" * 60)

    if args.dry_run:
        return 0

    records: list[RunRecord] = []
    for path, variant, seed in plan:
        if not args.force and _result_exists(path, seed):
            logger.info("Skipping %s seed %d (results already present)", variant.name, seed)
            records.append(RunRecord(variant.name, seed, "skipped", 0.0))
            continue

        record = run_one(path, seed, args.data_root, args.log_level)
        record.variant = variant.name
        records.append(record)
        logger.info(
            "%s seed %d -> %s in %.1f min", variant.name, seed, record.status, record.seconds / 60
        )

    summary_path = Path("results") / "experiment_runs.json"
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(
        json.dumps([r.__dict__ for r in records], indent=2), encoding="utf-8"
    )

    logger.info("=" * 60)
    for record in records:
        logger.info(
            "  %-16s seed %-4d %-8s %6.1f min %s",
            record.variant, record.seed, record.status,
            record.seconds / 60, record.error or "",
        )
    logger.info("Summary -> %s", summary_path)

    failures = [r for r in records if r.status == "failed"]
    if failures:
        logger.error("%d run(s) failed; the tables will be incomplete", len(failures))
        return 1
    logger.info("All runs complete. Generate the tables with:")
    logger.info("  python scripts/generate_paper_tables.py --results-dir results")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
